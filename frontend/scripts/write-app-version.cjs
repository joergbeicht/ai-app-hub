#!/usr/bin/env node
/**
 * Writes frontend/src/app/core/app-version.ts from, in order of precedence:
 * 1) process.env.APP_VERSION (required for Docker/CI without a git checkout)
 * 2) nearest SemVer git tag (`git describe --tags --abbrev=0`)
 *
 * No silent fallback to package.json – a missing version is a hard error.
 * Called via prestart / prebuild (see package.json).
 */
const fs = require('node:fs');
const path = require('node:path');
const { resolveAppVersion } = require('./lib/resolve-app-version.cjs');

const frontendRoot = path.resolve(__dirname, '..');
const outPath = path.join(frontendRoot, 'src/app/core/app-version.ts');

const version = resolveAppVersion();

if (!version) {
  console.error(`
[write-app-version] ERROR: No app version available.

Expected one of:
  1) Environment variable APP_VERSION (e.g. APP_VERSION=1.0.0)
  2) A SemVer git tag on this repository (e.g. git tag v1.0.0)

There is no fallback to package.json – that would invent a fake version.

Next steps:
  • Create and push a tag:  git tag v1.0.0 && git push origin v1.0.0
  • Or pass the version explicitly:  APP_VERSION=1.0.0 npm start
  • Docker: use ./start-docker.sh (resolves the tag on the host)
`);
  process.exit(1);
}

const content = `/**
 * Visible app version (toolbar).
 * Generated by scripts/write-app-version.cjs - do not edit manually.
 * Source: APP_VERSION env | git tag (no package.json fallback)
 */
export const APP_VERSION = '${version}';
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, content, 'utf8');

console.log(`[write-app-version] APP_VERSION=${version}`);
